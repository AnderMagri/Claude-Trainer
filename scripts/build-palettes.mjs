// Builds css/palettes.css: the extra colour palettes for the line colours (l1 … l6, lx).
// Sunset is the default and lives in css/tokens.css. Each palette here gets light and dark values,
// generated in OKLCH so every line has the same lightness, then checked for contrast:
//   -ink on -soft and on the page ≥ 4.5:1 (text), the line colour on the page ≥ 3:1 (tracks, rings).
// Run: node scripts/build-palettes.mjs   (prints the contrast check and writes css/palettes.css)
import { writeFileSync, readFileSync } from 'node:fs';

// name → hues for Line 1 … Line 7 (OKLCH hue angles) and chroma
const PALETTES = {
  ocean: { label: 'Ocean', hues: [175, 192, 210, 228, 245, 262, 280], chroma: 0.13 },
  forest: { label: 'Forest', hues: [95, 118, 138, 152, 165, 180, 198], chroma: 0.12 }
};
const LINES = ['l1', 'l2', 'l3', 'l4', 'l5', 'l6', 'lx'];
const GROUND = { light: '#F8F8FF', dark: '#0B0B0C' };
const SURFACE = { light: '#FFFFFF', dark: '#161617' };

// --- colour maths (OKLCH → sRGB) ---
function oklchToRgb(L, C, h) {
  const a = C * Math.cos((h * Math.PI) / 180), b = C * Math.sin((h * Math.PI) / 180);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.2914855480 * b;
  const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
  ];
  return lin.map((x) => { const v = x <= 0.0031308 ? 12.92 * x : 1.055 * Math.pow(Math.max(x, 0), 1 / 2.4) - 0.055; return Math.min(1, Math.max(0, v)); });
}
// reduce chroma until the colour fits in sRGB
function fit(L, C, h) {
  for (let c = C; c >= 0; c -= 0.005) {
    const a = c * Math.cos((h * Math.PI) / 180), b = c * Math.sin((h * Math.PI) / 180);
    const l_ = L + 0.3963377774 * a + 0.2158037573 * b, m_ = L - 0.1055613458 * a - 0.0638541728 * b, s_ = L - 0.0894841775 * a - 1.2914855480 * b;
    const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
    const lin = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s];
    if (lin.every((x) => x >= -1e-4 && x <= 1 + 1e-4)) return hex(oklchToRgb(L, c, h));
  }
  return hex(oklchToRgb(L, 0, h));
}
const hex = (rgb) => '#' + rgb.map((v) => Math.round(v * 255).toString(16).padStart(2, '0')).join('').toUpperCase();
const rgbOf = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const lum = (h) => { const [r, g, b] = rgbOf(h).map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4)); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const contrast = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };
const mix = (a, b, t) => hex(rgbOf(a).map((v, i) => v * t + rgbOf(b)[i] * (1 - t)));

function build(p, mode) {
  const out = {}, report = [];
  p.hues.forEach((h, i) => {
    const k = LINES[i];
    // the line colour: same lightness for all lines
    let L = mode === 'light' ? 0.62 : 0.74;
    let c = fit(L, p.chroma, h);
    while (contrast(c, GROUND[mode]) < 3 && L > 0.3 && L < 0.95) { L += mode === 'light' ? -0.01 : 0.01; c = fit(L, p.chroma, h); }
    const soft = mode === 'light' ? mix(c, '#FFFFFF', 0.17) : mix(c, SURFACE.dark, 0.14);
    // text colour: darker (light) or lighter (dark) until it reads on soft and on the page
    let Li = mode === 'light' ? 0.45 : 0.84, ink = fit(Li, p.chroma, h);
    while ((contrast(ink, soft) < 4.6 || contrast(ink, GROUND[mode]) < 4.6) && Li > 0.2 && Li < 0.98) { Li += mode === 'light' ? -0.01 : 0.01; ink = fit(Li, p.chroma, h); }
    const on = contrast(c, '#FFFFFF') >= contrast(c, '#111114') ? '#FFFFFF' : '#111114';
    out[k] = { c, ink, soft, on };
    report.push(`${k} ${c} (${contrast(c, GROUND[mode]).toFixed(1)}:1 page)  ink ${ink} (${contrast(ink, soft).toFixed(1)}:1 on soft)  on ${on} (${contrast(c, on).toFixed(1)}:1)`);
  });
  return { out, report };
}
const decl = (o) => LINES.map((k) => `--${k}: ${o[k].c}; --${k}-ink: ${o[k].ink}; --${k}-soft: ${o[k].soft}; --on-${k}: ${o[k].on};`).join('\n  ');

let css = '/* Generated by scripts/build-palettes.mjs. Do not edit by hand. Sunset (the default) is in tokens.css. */\n';
// Each palette card in Settings shows its own colours, whatever palette is active: the same values are
// also set on .pal[data-pal="…"]. Sunset's values are read from tokens.css.
const tokens = readFileSync(new URL('../css/tokens.css', import.meta.url), 'utf8');
const grab = (block) => { const o = {}; for (const k of LINES) { const m = (q) => (block.match(new RegExp(`--${q}:\\s*(#[0-9A-Fa-f]{6})`)) || [])[1]; o[k] = { c: m(k), ink: m(k + '-ink'), soft: m(k + '-soft'), on: m('on-' + k) }; } return o; };
const sunsetLight = grab(tokens.slice(tokens.indexOf(':root {'), tokens.indexOf('@media')));
const sunsetDark = grab(tokens.slice(tokens.indexOf(':root[data-theme="dark"]')));
const cardRules = (name, Lo, Do) => `.pal[data-pal="${name}"] {\n  ${decl(Lo)}\n}\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) .pal[data-pal="${name}"] {\n  ${decl(Do)}\n  }\n}\n:root[data-theme="dark"] .pal[data-pal="${name}"] {\n  ${decl(Do)}\n}\n`;
css += '\n/* Sunset (for its Settings card) */\n' + cardRules('sunset', sunsetLight, sunsetDark);
for (const [name, p] of Object.entries(PALETTES)) {
  const L = build(p, 'light'), D = build(p, 'dark');
  console.log(`\n${p.label} light\n  ` + L.report.join('\n  ') + `\n${p.label} dark\n  ` + D.report.join('\n  '));
  css += `\n/* ${p.label} */\n:root[data-palette="${name}"] {\n  ${decl(L.out)}\n  --mark: ${L.out.l2.c}55; --mark-strong: ${L.out.l2.c};\n}\n`;
  css += `@media (prefers-color-scheme: dark) {\n  :root[data-palette="${name}"]:not([data-theme="light"]) {\n  ${decl(D.out)}\n  --mark: ${D.out.l2.c}44; --mark-strong: ${D.out.l2.c};\n  }\n}\n`;
  css += `:root[data-palette="${name}"][data-theme="dark"] {\n  ${decl(D.out)}\n  --mark: ${D.out.l2.c}44; --mark-strong: ${D.out.l2.c};\n}\n`;
  css += cardRules(name, L.out, D.out);
}
writeFileSync(new URL('../css/palettes.css', import.meta.url), css);
console.log('\nwrote css/palettes.css');
