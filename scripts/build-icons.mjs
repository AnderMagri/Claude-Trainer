// Builds js/icons.js from the Lucide SVG files in assets/icons/.
// The course uses its own short icon names; MAP says which Lucide file each one is.
//
//   node scripts/build-icons.mjs                 rebuild js/icons.js from assets/icons/
//   node scripts/build-icons.mjs <lucide-dir>    first copy the needed SVGs from a lucide-static
//                                                 folder (node_modules/lucide-static), then rebuild
//
// Icons: Lucide (https://lucide.dev), ISC licence. See assets/icons/LICENSE.
import { readFileSync, writeFileSync, copyFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets/icons');

const MAP = {
  map: 'map', book: 'book-open', exam: 'clipboard-check', glossary: 'book-a', prefs: 'sliders-horizontal',
  back: 'arrow-left', next: 'arrow-right', check: 'check', bookmark: 'bookmark', marker: 'highlighter',
  note: 'notebook-pen', star: 'star', copy: 'copy', trash: 'trash-2', edit: 'pencil', external: 'external-link',
  speaker: 'volume-2', stop: 'square', pause: 'pause', bulb: 'lightbulb', alert: 'triangle-alert', target: 'target',
  analogy: 'shapes', simple: 'feather', try: 'flask-conical', terminal: 'terminal', chat: 'message-circle',
  ask: 'message-circle-question', flag: 'flag', clock: 'clock', download: 'download', upload: 'upload', x: 'x',
  loop: 'repeat', plug: 'plug', branch: 'git-branch', rocket: 'rocket', cube: 'box', key: 'key-round',
  shield: 'shield', spark: 'sparkles', play: 'play', search: 'search', plus: 'plus', reset: 'rotate-ccw',
  award: 'award', cloud: 'cloud', device: 'smartphone', list: 'list', toc: 'table-of-contents',
  dollar: 'circle-dollar-sign', eye: 'eye', sort: 'arrow-up-down', code: 'code', globe: 'globe', dice: 'dices',
  layers: 'layers', users: 'users', server: 'server', folder: 'folder', wand: 'wand-sparkles', gauge: 'gauge',
  menu: 'menu', sun: 'sun', moon: 'moon', rule: 'scroll-text', send: 'arrow-up', down: 'chevron-down',
  headphones: 'headphones'
};
// Filled twins: same outline, painted with the current colour.
const FILLED = { bookmarkOn: 'bookmark', starOn: 'star' };

const from = process.argv[2];
if (from) {
  mkdirSync(dir, { recursive: true });
  for (const f of new Set(Object.values(MAP))) copyFileSync(join(from, 'icons', f + '.svg'), join(dir, f + '.svg'));
  if (existsSync(join(from, 'LICENSE'))) copyFileSync(join(from, 'LICENSE'), join(dir, 'LICENSE'));
}

const inner = (file) => {
  const svg = readFileSync(join(dir, file + '.svg'), 'utf8');
  return svg.replace(/<!--[\s\S]*?-->/g, '').replace(/<svg[\s\S]*?>/, '').replace('</svg>', '')
    .replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
};

const out = {};
for (const [name, file] of Object.entries(MAP)) out[name] = inner(file);
for (const [name, file] of Object.entries(FILLED)) out[name] = '<g fill="currentColor">' + inner(file) + '</g>';

const js = '/* Generated by scripts/build-icons.mjs from assets/icons/ (Lucide, ISC licence). Do not edit by hand. */\n' +
  'window.CT_ICONS = ' + JSON.stringify(out, null, 1) + ';\n';
writeFileSync(join(root, 'js/icons.js'), js);
console.log('wrote js/icons.js:', Object.keys(out).length, 'icons,', js.length, 'bytes');
